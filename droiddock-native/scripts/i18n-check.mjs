#!/usr/bin/env node
// Lists English keys used via tr("…") / tn("…","…") in the Swift sources that are missing from each
// language's Localizable.strings. Writes docs/I18N-MISSING.md. Does not translate anything.
// Usage: node scripts/i18n-check.mjs
import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "mac/Sources/DroidDock");
const res = join(src, "Resources");

const unescape = (s) =>
  s.replace(/\\(["\\nt])/g, (_, c) => ({ '"': '"', "\\": "\\", n: "\n", t: "\t" }[c]));

function walk(dir, out = []) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) { if (f !== "Resources") walk(p, out); }
    else if (f.endsWith(".swift")) out.push(p);
  }
  return out;
}

const LIT = String.raw`"((?:[^"\\\n]|\\.)*)"`;
const trRe = new RegExp(String.raw`\btr\(\s*${LIT}`, "g");
const tnRe = new RegExp(String.raw`\btn\(\s*${LIT}\s*,\s*${LIT}`, "g");

const used = new Map(); // key -> first file:line
for (const file of walk(src)) {
  const text = readFileSync(file, "utf8");
  const add = (raw, idx) => {
    if (raw.includes("\\(")) return; // interpolated: not a static key
    const ls = text.lastIndexOf("\n", idx) + 1;
    if (/^\s*\/\//.test(text.slice(ls, idx))) return; // comment line
    const key = unescape(raw);
    if (!used.has(key)) used.set(key, `${relative(root, file)}:${text.slice(0, idx).split("\n").length}`);
  };
  for (const m of text.matchAll(trRe)) add(m[1], m.index);
  for (const m of text.matchAll(tnRe)) { add(m[1], m.index); add(m[2], m.index); }
}

const lineRe = new RegExp(String.raw`^${LIT}\s*=\s*${LIT}\s*;`);
const langs = readdirSync(res).filter((d) => d.endsWith(".lproj")).map((d) => d.replace(".lproj", "")).sort();
const report = [];
let total = 0;
for (const lang of langs) {
  if (lang === "en") continue; // English is the key itself
  const f = join(res, `${lang}.lproj`, "Localizable.strings");
  const have = new Set();
  if (existsSync(f)) for (const l of readFileSync(f, "utf8").split("\n")) { const m = l.match(lineRe); if (m) have.add(unescape(m[1])); }
  const missing = [...used.keys()].filter((k) => !have.has(k)).sort();
  total += missing.length;
  report.push({ lang, have: have.size, missing });
}

let md = `# Missing translations\n\nGenerated by \`scripts/i18n-check.mjs\`. Static \`tr(...)\`/\`tn(...)\` keys found in Swift: **${used.size}**.\n\n`;
md += `| Language | Keys in file | Missing |\n|---|---|---|\n`;
for (const r of report) md += `| ${r.lang} | ${r.have} | ${r.missing.length} |\n`;
const base = report[0]?.missing ?? [];
const common = base.filter((k) => report.every((r) => r.missing.includes(k)));
md += `\nKeys missing in **every** language: ${common.length}\n\n`;
for (const k of common) md += `- \`${k.replace(/\n/g, "\\n")}\` (${used.get(k)})\n`;
const partial = report.filter((r) => r.missing.some((k) => !common.includes(k)));
for (const r of partial) {
  md += `\n## ${r.lang}: also missing\n\n`;
  for (const k of r.missing.filter((k) => !common.includes(k))) md += `- \`${k.replace(/\n/g, "\\n")}\`\n`;
}
writeFileSync(join(root, "docs/I18N-MISSING.md"), md);
console.log(`${used.size} keys, ${langs.length - 1} languages, ${total} missing entries -> docs/I18N-MISSING.md`);
