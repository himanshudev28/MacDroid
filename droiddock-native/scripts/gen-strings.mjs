#!/usr/bin/env node
// Generates Resources/<lproj>.lproj/Localizable.strings from the Tauri app's
// TypeScript catalogs (droiddock-tauri/app/src/locales/*.ts).
// Usage: node scripts/gen-strings.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "..", "droiddock-tauri", "app", "src", "locales");
const out = join(here, "..", "mac", "Sources", "DroidDock", "Resources");

// TS catalog code -> Apple lproj name. Keep in sync with L10n.swift `languages`.
const LPROJ = { zh: "zh-Hans", zh_Hant: "zh-Hant" };

function parseCatalog(file) {
  let code = readFileSync(file, "utf8")
    .replace(/^\s*import\s[^\n]*\n/gm, "")
    .replace(/export\s+const\s+(\w+)\s*:\s*Catalog\s*=/, "globalThis.__cat =");
  const ctx = { globalThis: {} };
  vm.createContext(ctx);
  vm.runInContext(code, ctx, { timeout: 5000 });
  const cat = ctx.globalThis.__cat;
  if (!cat || typeof cat !== "object") throw new Error(`no catalog in ${file}`);
  return cat;
}

const esc = (s) =>
  s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n").replace(/\r/g, "\\r").replace(/\t/g, "\\t");

const counts = {};
for (const f of readdirSync(src).filter((n) => n.endsWith(".ts")).sort()) {
  const code = basename(f, ".ts");
  const cat = parseCatalog(join(src, f));
  const lproj = LPROJ[code] ?? code;
  // Extra translations for strings added in the native app (i18n/<code>.json, English key → text).
  const extraPath = join(here, "..", "i18n", `${code}.json`);
  try { Object.assign(cat, JSON.parse(readFileSync(extraPath, "utf8"))); } catch {}
  const keys = Object.keys(cat).sort();
  const body = keys.map((k) => `"${esc(k)}" = "${esc(cat[k])}";`).join("\n");
  const dir = join(out, `${lproj}.lproj`);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "Localizable.strings"),
    `/* Generated by scripts/gen-strings.mjs from ${f} - do not edit. */\n${body}\n`, "utf8");
  counts[lproj] = keys.length;
}
const enDir = join(out, "en.lproj");
mkdirSync(enDir, { recursive: true });
writeFileSync(join(enDir, "Localizable.strings"),
  "/* English: the keys are the English text, so this file is intentionally empty. */\n", "utf8");
console.log(counts);
