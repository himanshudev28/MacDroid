#!/usr/bin/env node
// i18n-extra/<code>.json (English key -> translation) -> app/.../i18n/LocaleExtra_<code>.kt
// Usage: node tools/i18n-extra-gen.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const inDir = path.join(root, 'i18n-extra');
const outDir = path.join(root, 'app/src/main/java/com/droiddock/app/i18n');

export const CODES = 'ar bn de es fr hi id it ja ko pt ru tr vi zh zh_Hant'.split(' ');

function kt(s) {
  let o = '';
  for (const ch of s) {
    const c = ch.codePointAt(0);
    if (ch === '\\') o += '\\\\';
    else if (ch === '"') o += '\\"';
    else if (ch === '$') o += '\\$';
    else if (ch === '\n') o += '\\n';
    else if (ch === '\r') o += '\\r';
    else if (ch === '\t') o += '\\t';
    else if (c < 0x20) o += '\\u' + c.toString(16).padStart(4, '0');
    else o += ch;
  }
  return `"${o}"`;
}

fs.mkdirSync(outDir, { recursive: true });
for (const code of CODES) {
  const f = path.join(inDir, `${code}.json`);
  let data = {};
  if (fs.existsSync(f)) {
    try { data = JSON.parse(fs.readFileSync(f, 'utf8')); }
    catch (e) { console.error(`${code}.json: invalid JSON: ${e.message}`); process.exit(1); }
  }
  if (data === null || typeof data !== 'object' || Array.isArray(data)) {
    console.error(`${code}.json: must be an object {"English": "Translation"}`); process.exit(1);
  }
  const lines = Object.keys(data).sort().filter(k => {
    if (typeof data[k] !== 'string') { console.error(`${code}.json: value for "${k}" is not a string`); process.exit(1); }
    return data[k].trim() !== '';   // blank = not translated yet
  }).map(k => `    ${kt(k)} to ${kt(data[k])},`);
  const body = `// Generated by tools/i18n-extra-gen.mjs from i18n-extra/${code}.json — edit the JSON, not this.
package com.droiddock.app.i18n

internal val extra_${code}: Map<String, String> = mapOf(
${lines.join('\n')}
)
`;
  fs.writeFileSync(path.join(outDir, `LocaleExtra_${code}.kt`), body);
  console.log(`${code}: ${lines.length} extra strings`);
}
